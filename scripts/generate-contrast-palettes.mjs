// Generates src/styles/palettes-contrast.css: medium and high contrast versions (light and dark) of every
// built-in palette, for `[data-contrast='medium' | 'high']` on <html>. Run: node scripts/generate-contrast-palettes.mjs
//
// The built-in palettes come from material-color-utilities' classic themeFromSourceColor (see palettes.css), which
// has no contrast levels. Contrast lives in the newer DynamicScheme, so each palette's own tonal palettes
// (primary, secondary, tertiary, neutral, neutral variant, error, from the same classic theme) are fed to a
// DynamicScheme at contrast 0.5 (medium) and 1 (high): the hues and chroma stay the palette's, only the tones
// spread apart. Monochrome is hand-made, so it uses SchemeMonochrome. The standard level stays palettes.css.
import { registerHooks } from 'node:module'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')

// material-color-utilities 0.4.0 ships an extensionless relative import Node can't resolve on its own
registerHooks({
  resolve(spec, ctx, next) {
    try {
      return next(spec, ctx)
    } catch (e) {
      if (spec.startsWith('.') && !spec.endsWith('.js')) return next(`${spec}.js`, ctx)
      throw e
    }
  },
})
const mcu = await import(path.join(root, 'node_modules/@material/material-color-utilities/index.js'))

// Same role list as src/composables/dynamicColor.ts (success* is a library extension and isn't generated)
const roles = [
  'primary', 'on-primary', 'primary-container', 'on-primary-container',
  'secondary', 'on-secondary', 'secondary-container', 'on-secondary-container',
  'tertiary', 'on-tertiary', 'tertiary-container', 'on-tertiary-container',
  'error', 'on-error', 'error-container', 'on-error-container',
  'background', 'on-background',
  'surface', 'on-surface', 'surface-variant', 'on-surface-variant',
  'surface-dim', 'surface-bright',
  'surface-container-lowest', 'surface-container-low', 'surface-container',
  'surface-container-high', 'surface-container-highest',
  'outline', 'outline-variant',
  'inverse-surface', 'inverse-on-surface', 'inverse-primary',
  'primary-fixed', 'primary-fixed-dim', 'on-primary-fixed', 'on-primary-fixed-variant',
  'secondary-fixed', 'secondary-fixed-dim', 'on-secondary-fixed', 'on-secondary-fixed-variant',
  'tertiary-fixed', 'tertiary-fixed-dim', 'on-tertiary-fixed', 'on-tertiary-fixed-variant',
]
const camel = (role) => role.replace(/-([a-z])/g, (_, c) => c.toUpperCase())
const colors = new mcu.MaterialDynamicColors()

function scheme(id, seed, isDark, contrastLevel) {
  const sourceColorHct = mcu.Hct.fromInt(mcu.argbFromHex(seed))
  if (id === 'monochrome') return new mcu.SchemeMonochrome(sourceColorHct, isDark, contrastLevel)
  const p = mcu.themeFromSourceColor(mcu.argbFromHex(seed)).palettes
  return new mcu.DynamicScheme({
    sourceColorHct,
    variant: mcu.Variant.TONAL_SPOT,
    contrastLevel,
    isDark,
    primaryPalette: p.primary,
    secondaryPalette: p.secondary,
    tertiaryPalette: p.tertiary,
    neutralPalette: p.neutral,
    neutralVariantPalette: p.neutralVariant,
    errorPalette: p.error,
  })
}

function block(selector, s) {
  const lines = roles.map((role) => {
    const color = colors[camel(role)]?.call(colors)
    return color ? `  --color-${role}: ${mcu.hexFromArgb(color.getArgb(s)).toUpperCase()};` : null
  }).filter(Boolean)
  return `${selector} {\n${lines.join('\n')}\n}\n`
}

// The palette list is useColorPalette.ts' `palettes` array (id + seed)
const source = fs.readFileSync(path.join(root, 'src/composables/useColorPalette.ts'), 'utf8')
const palettes = [...source.matchAll(/\{\s*id:\s*'([\w-]+)',\s*label:\s*'[^']*',\s*seed:\s*'(#[0-9A-Fa-f]{6})'\s*\}/g)]
  .map(([, id, seed]) => ({ id, seed }))
if (palettes.length < 40) throw new Error(`Expected the 40 built-in palettes in useColorPalette.ts, found ${palettes.length}`)

const levels = [['medium', 0.5], ['high', 1]]
let css = `/* Generated by scripts/generate-contrast-palettes.mjs — don't edit by hand.
   Medium and high contrast for the built-in palettes: set data-contrast='medium' | 'high' on <html>
   (createM3UI({ contrast }) or useColorPalette().setContrast()). Light blocks exclude .dark: otherwise they
   would tie with palettes.css' dark blocks on specificity and win by source order. */
`
for (const { id, seed } of palettes) {
  // Purple is the baseline in theme.css, used when <html> has no data-palette
  const base = id === 'purple' ? "html:not([data-palette])" : `[data-palette='${id}']`
  css += `\n/* ─── ${id} ─── */\n`
  for (const [level, contrast] of levels) {
    css += block(`${base}[data-contrast='${level}']:not(.dark)`, scheme(id, seed, false, contrast))
    css += block(`${base}[data-contrast='${level}'].dark`, scheme(id, seed, true, contrast))
  }
}

const out = path.join(root, 'src/styles/palettes-contrast.css')
fs.writeFileSync(out, css)
console.log(`Contrast palettes: ${palettes.length} palettes × ${levels.length} levels → ${path.relative(root, out)} (${(css.length / 1024).toFixed(0)} KB)`)
