#!/usr/bin/env node
/*
 * Regenerates the emoji data from the official sources:
 * - Unicode's emoji-test.txt: the emoji, their CLDR order, groups, versions and skin-tone variants.
 * - CLDR annotations (npm cldr-annotations-full / cldr-annotations-derived-full): names and search
 *   keywords in every language the library ships.
 *
 * Writes src/data/emojis.ts (categories, loaded with the components) and
 * src/data/emoji-names/emoji-names-<lang>.ts (names and keywords, loaded on demand, one chunk per language).
 *
 *   node scripts/generate-emoji-data.mjs
 *
 * Bump EMOJI_VERSION when a newer Emoji version renders on the platforms you care about.
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const EMOJI_VERSION = 15.0 // Windows 11, Android 14, iOS 16.4 and later render all of it
const UNICODE_TEST = 'https://unicode.org/Public/emoji/15.1/emoji-test.txt'
const CLDR = '48.2.0'
const LANGS = ['en', 'es', 'fr', 'pt', 'de', 'ja', 'zh', 'ko']

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const TONES = ['\u{1F3FB}', '\u{1F3FC}', '\u{1F3FD}', '\u{1F3FE}', '\u{1F3FF}']
const TONE_NAMES = ['light skin tone', 'medium-light skin tone', 'medium skin tone', 'medium-dark skin tone', 'dark skin tone']

// Unicode groups/subgroups → the library's category ids (kept from the hand-written data).
function categoryOf(group, subgroup) {
  if (group === 'Smileys & Emotion') return 'smileys'
  if (group === 'People & Body') return subgroup.startsWith('hand') || subgroup === 'body-parts' ? 'gestures' : 'people'
  if (group === 'Animals & Nature') return subgroup.startsWith('plant') ? 'nature' : 'animals'
  if (group === 'Food & Drink') return 'food'
  if (group === 'Travel & Places') return subgroup === 'sky & weather' ? 'nature' : 'travel'
  if (group === 'Activities') return 'activities'
  if (group === 'Objects') return 'objects'
  if (group === 'Symbols') return 'symbols'
  if (group === 'Flags') return 'flags'
  return null // Component: skin tone swatches and hair styles
}
const CATEGORIES = [
  ['smileys', 'Smileys', 'sentiment_satisfied'],
  ['gestures', 'Gestures', 'waving_hand'],
  ['people', 'People', 'group'],
  ['animals', 'Animals', 'pets'],
  ['nature', 'Nature', 'eco'],
  ['food', 'Food', 'restaurant'],
  ['activities', 'Activities', 'sports_esports'],
  ['travel', 'Travel', 'flight'],
  ['objects', 'Objects', 'lightbulb'],
  ['symbols', 'Symbols', 'favorite'],
  ['flags', 'Flags', 'flag'],
]

/** The one-modifier variant, the way MEmojiSelector derives it at runtime. */
function withTone(base, tone) {
  const [first, ...rest] = [...base]
  if (rest[0] === '️') rest.shift()
  return first + tone + rest.join('')
}

const text = await (await fetch(UNICODE_TEST)).text()
let group = ''
let subgroup = ''
const bases = [] // { emoji, name, category }
const byName = new Map()
for (const line of text.split('\n')) {
  if (line.startsWith('# group:')) group = line.slice(8).trim()
  else if (line.startsWith('# subgroup:')) subgroup = line.slice(11).trim()
  const m = /^([0-9A-F ]+?)\s*; fully-qualified\s*# (\S+) E(\d+\.\d+) (.+)$/.exec(line)
  if (!m) continue
  const [, , emoji, version, name] = m
  if (Number(version) > EMOJI_VERSION) continue
  byName.set(name, emoji)
  if (name.includes('skin tone')) continue
  const category = categoryOf(group, subgroup)
  if (category) bases.push({ emoji, name, category })
}

// An emoji takes a skin tone when all five one-tone variants exist and match the derivation rule.
const toneable = bases
  .filter(({ emoji, name }) => TONE_NAMES.every((t, i) => byName.get(`${name}: ${t}`) === withTone(emoji, TONES[i])))
  .map((b) => b.emoji)

const categories = CATEGORIES.map(([id, label, icon]) => ({ id, label, icon, emojis: bases.filter((b) => b.category === id).map((b) => b.emoji) }))
const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

writeFileSync(
  resolve(root, 'src/data/emojis.ts'),
  `// Generated by scripts/generate-emoji-data.mjs from Unicode emoji-test.txt (Emoji ${EMOJI_VERSION}). Don't edit by hand.
// Emoji data © Unicode, Inc., under the Unicode License v3 (dist/THIRD_PARTY_LICENSES.md, scripts/licenses/unicode-license-v3.txt).

export interface EmojiCategory {
  id: string
  /** English name; MEmojiSelector shows the locale's (emojiCategory* keys). */
  label: string
  icon: string
  emojis: string[]
}

export const emojiCategories: EmojiCategory[] = [
${categories.map((c) => `  { id: ${q(c.id)}, label: ${q(c.label)}, icon: ${q(c.icon)}, emojis: [${c.emojis.map(q).join(',')}] },`).join('\n')}
]

/** Emoji that take a skin tone (all five one-tone variants exist). */
export const toneableEmojis = new Set<string>([${toneable.map(q).join(',')}])

/** The five Fitzpatrick modifiers, light to dark. */
export const skinTones = [${TONES.map(q).join(', ')}] as const

/** \`emoji\` with skin tone \`tone\` (0 = none, 1–5 = light to dark), if it takes one. */
export function withSkinTone(emoji: string, tone: number): string {
  const modifier = skinTones[tone - 1]
  if (!modifier || !toneableEmojis.has(emoji)) return emoji
  const [first, ...rest] = [...emoji]
  if (rest[0] === '\\uFE0F') rest.shift()
  return first + modifier + rest.join('')
}

export const allEmojis = emojiCategories.flatMap((c) => c.emojis)

export function randomEmoji(from?: string[]): string {
  const pool = from ?? allEmojis
  return pool[Math.floor(Math.random() * pool.length)]!
}
`,
)

// Names and keywords: "name|keyword|keyword…", keyed by the emoji as it appears in the categories.
mkdirSync(resolve(root, 'src/data/emoji-names'), { recursive: true })
for (const lang of LANGS) {
  const base = 'https://cdn.jsdelivr.net/npm'
  const ann = (await (await fetch(`${base}/cldr-annotations-full@${CLDR}/annotations/${lang}/annotations.json`)).json()).annotations.annotations
  const der = (await (await fetch(`${base}/cldr-annotations-derived-full@${CLDR}/annotationsDerived/${lang}/annotations.json`)).json()).annotationsDerived.annotations
  const entries = []
  let missing = 0
  for (const { emoji, name } of bases) {
    const key = emoji.replace(/️/g, '')
    const a = ann[key] ?? der[key] ?? ann[emoji] ?? der[emoji]
    if (!a) missing++
    const tts = a?.tts?.[0] ?? (lang === 'en' ? name : null)
    if (!tts) continue
    const words = [tts, ...(a?.default ?? []).filter((w) => w !== tts)]
    entries.push(`  ${q(emoji)}: ${q(words.join('|'))},`)
  }
  writeFileSync(
    resolve(root, `src/data/emoji-names/emoji-names-${lang}.ts`),
    `// Generated by scripts/generate-emoji-data.mjs from CLDR ${CLDR} annotations (${lang}). Don't edit by hand.\n// Emoji data © Unicode, Inc., under the Unicode License v3 (dist/THIRD_PARTY_LICENSES.md, scripts/licenses/unicode-license-v3.txt).\n// "name|keyword|keyword…" per emoji.\nconst names: Record<string, string> = {\n${entries.join('\n')}\n}\nexport default names\n`,
  )
  console.log(`${lang}: ${entries.length} names, ${missing} without CLDR annotations`)
}
console.log(`${bases.length} emoji in ${categories.length} categories, ${toneable.length} with skin tones`)
